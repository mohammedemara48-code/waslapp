import { chromium } from "playwright";
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 860 } });
const cons = [];
page.on("console", (m) => { if (m.type() === "error") cons.push(m.text()); });
page.on("pageerror", (e) => cons.push(String(e)));
await page.goto("http://127.0.0.1:8080/", { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.getByRole("button", { name: "رقم الجوال" }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: "/workspace/screenshots/phone-signup.png", fullPage: true });
const phoneText = await page.locator("body").innerText();
await page.getByRole("button", { name: "تثبيت" }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: "/workspace/screenshots/install-dialog.png" });
await page.goto("http://127.0.0.1:8080/friends", { waitUntil: "networkidle" });
await page.waitForTimeout(600);
const friendsUrl = page.url();
const friendsText = (await page.locator("body").innerText()).slice(0, 180);
console.log(JSON.stringify({ cons, phoneHasUser: phoneText.includes("اسم المستخدم"), phoneHasSmsNote: phoneText.includes("SMS"), friendsUrl, friendsText, cons2: cons }, null, 2));
await browser.close();
